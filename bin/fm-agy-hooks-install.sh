#!/usr/bin/env bash
# Install (or remove) firstmate's single owned entry in agy's GLOBAL hooks file.
#
# agy discovers hooks from ~/.gemini/config/hooks.json. That file is the
# captain's own global customization surface and may hold unrelated entries, so
# this installer owns exactly ONE top-level key and never rewrites the rest:
#
#   "firstmate-turn-end": { "Stop": [ { "command": <shim>, "timeout": <n> } ] }
#
# Verified against agy 1.1.10: the workspace-level .agents/hooks.json is NOT
# loaded by the CLI, so a per-worktree hook is not an option and the global file
# is the only surface that works. bin/fm-agy-stop-hook.sh is the guarded no-op
# that makes one global hook safe for sessions firstmate did not launch.
#
# The registered command is a small generated SHIM rather than a direct path
# into one checkout's bin/. Several firstmate homes can share one machine (and
# one global hooks.json), so the shim resolves the real hook out of the
# validated FM_AGY_HOOK_ROOT the launch exported. That keeps the global file
# stable no matter which checkout installed it last.
#
# Usage:
#   fm-agy-hooks-install.sh install [--timeout <seconds>]
#   fm-agy-hooks-install.sh remove
#   fm-agy-hooks-install.sh status
set -u

HOOK_KEY=firstmate-turn-end
GEMINI_CONFIG="${FM_AGY_CONFIG_DIR:-${GEMINI_HOME:-$HOME/.gemini}/config}"
HOOKS_JSON="$GEMINI_CONFIG/hooks.json"
SHIM="$GEMINI_CONFIG/fm-firstmate-stop.sh"

# The hook timeout must exceed the checkpoint bound in bin/fm-agy-stop-hook.sh,
# or agy kills the checkpoint mid-wait. agy's own default is 30s, which is far
# too short; a 45s hook under a 90s timeout was verified to complete.
DEFAULT_TIMEOUT=$(( ${FM_AGY_STOP_CHECKPOINT:-240} + 60 ))

usage() { sed -n '2,24p' "$0" | sed 's/^# \{0,1\}//'; }

need_jq() {
  command -v jq >/dev/null 2>&1 || {
    echo "error: jq is required to edit $HOOKS_JSON without disturbing other entries" >&2
    exit 1
  }
}

write_shim() {
  mkdir -p "$GEMINI_CONFIG" || return 1
  cat > "$SHIM" <<'EOF'
#!/usr/bin/env bash
# Generated by bin/fm-agy-hooks-install.sh - do not edit.
# Guarded dispatcher for firstmate's agy Stop hook. Every agy session on this
# machine runs this, so it must stay silent and inert unless firstmate launched
# the session and exported a valid hook root.
set -u
root=${FM_AGY_HOOK_ROOT:-}
hook=
case "$root" in
  /*) [ -x "$root/bin/fm-agy-stop-hook.sh" ] && hook="$root/bin/fm-agy-stop-hook.sh" ;;
esac
if [ -z "$hook" ]; then
  cat >/dev/null 2>&1 || true
  printf '{"decision":"allow"}\n'
  exit 0
fi
exec "$hook"
EOF
  chmod 0700 "$SHIM"
}

case "${1:-}" in
  install)
    shift
    timeout=$DEFAULT_TIMEOUT
    while [ "$#" -gt 0 ]; do
      case "$1" in
        --timeout) [ "$#" -gt 1 ] || { echo "error: --timeout requires a value" >&2; exit 2; }
                   timeout=$2; shift 2 ;;
        --timeout=*) timeout=${1#--timeout=}; shift ;;
        *) echo "error: unknown argument: $1" >&2; exit 2 ;;
      esac
    done
    case "$timeout" in ''|*[!0-9]*) echo "error: --timeout must be a whole number of seconds" >&2; exit 2 ;; esac
    need_jq
    write_shim || { echo "error: could not write $SHIM" >&2; exit 1; }
    [ -f "$HOOKS_JSON" ] || printf '{}\n' > "$HOOKS_JSON"
    # Reject a corrupt file rather than silently replacing the captain's hooks.
    jq -e 'type == "object"' "$HOOKS_JSON" >/dev/null 2>&1 || {
      echo "error: $HOOKS_JSON is not a JSON object; refusing to rewrite it" >&2
      exit 1
    }
    tmp=$(mktemp "$GEMINI_CONFIG/.hooks.json.XXXXXX") || exit 1
    if jq --arg k "$HOOK_KEY" --arg c "$SHIM" --argjson t "$timeout" \
        '.[$k] = {Stop: [{type: "command", command: $c, timeout: $t}]}' \
        "$HOOKS_JSON" > "$tmp"; then
      mv "$tmp" "$HOOKS_JSON"
      echo "agy hooks: installed $HOOK_KEY (timeout ${timeout}s) in $HOOKS_JSON"
    else
      rm -f "$tmp"
      echo "error: failed to update $HOOKS_JSON" >&2
      exit 1
    fi
    ;;
  remove)
    need_jq
    [ -f "$HOOKS_JSON" ] || { echo "agy hooks: nothing to remove"; exit 0; }
    tmp=$(mktemp "$GEMINI_CONFIG/.hooks.json.XXXXXX") || exit 1
    if jq --arg k "$HOOK_KEY" 'del(.[$k])' "$HOOKS_JSON" > "$tmp"; then
      mv "$tmp" "$HOOKS_JSON"
      rm -f "$SHIM"
      echo "agy hooks: removed $HOOK_KEY from $HOOKS_JSON"
    else
      rm -f "$tmp"
      echo "error: failed to update $HOOKS_JSON" >&2
      exit 1
    fi
    ;;
  status)
    if [ -f "$HOOKS_JSON" ] && command -v jq >/dev/null 2>&1 &&
       jq -e --arg k "$HOOK_KEY" 'has($k)' "$HOOKS_JSON" >/dev/null 2>&1; then
      echo "agy hooks: $HOOK_KEY installed in $HOOKS_JSON"
      [ -x "$SHIM" ] || echo "agy hooks: WARNING shim missing or not executable: $SHIM"
    else
      echo "agy hooks: $HOOK_KEY not installed"
      exit 1
    fi
    ;;
  -h|--help|'') usage ;;
  *) echo "error: unknown command: $1" >&2; usage >&2; exit 2 ;;
esac
